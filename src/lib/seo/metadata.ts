import type { Metadata } from "next";
import { site, siteUrl } from "@/config/site";

interface SocialImage {
  /** Path under /public, e.g. "/projects/x/cover.png". Resolved against the site URL. */
  url: string;
  alt: string;
  width?: number;
  height?: number;
}

interface PageMetadataOptions {
  title: string;
  description: string;
  /** Route path beginning with "/", used for the canonical URL. */
  path: string;
  /** Set for routes that should not appear in search results. */
  noIndex?: boolean;
  /** A page-specific social card image, e.g. a project's cover screenshot. */
  image?: SocialImage;
}

/**
 * Builds page metadata with a canonical URL and social card fields.
 *
 * Every page uses this instead of hand-writing a `metadata` object, so titles,
 * canonicals and social cards stay consistent.
 *
 * Social card images: by default none is set here, and the site-wide card
 * generated by `src/app/opengraph-image.tsx` is attached to every route by
 * Next. Passing `image` replaces it for that one page, which is how project
 * pages share their own screenshot.
 */
export function createMetadata({
  title,
  description,
  path,
  noIndex = false,
  image,
}: PageMetadataOptions): Metadata {
  const url = `${siteUrl}${path === "/" ? "" : path}`;

  return {
    title,
    description,
    alternates: { canonical: url },
    openGraph: {
      type: "website",
      siteName: site.name,
      title: `${title} — ${site.name}`,
      description,
      url,
      locale: "en_US",
      ...(image ? { images: [image] } : {}),
    },
    twitter: {
      card: "summary_large_image",
      title: `${title} — ${site.name}`,
      description,
      ...(image ? { images: [{ url: image.url, alt: image.alt }] } : {}),
    },
    robots: noIndex ? { index: false, follow: false } : undefined,
  };
}
